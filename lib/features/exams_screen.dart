class ExamsScreen extends StatelessWidget {
  const ExamsScreen({super.key});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: AuroraBackground(
        child: ValueListenableBuilder(
          valueListenable: DB.exams.listenable(),
          builder: (_, __, ___) => ValueListenableBuilder(
            valueListenable: DB.attempts.listenable(),
            builder: (_, __, ___) {
              final list = DB.exams.values.toList()
                ..sort((a, b) => b.createdMs.compareTo(a.createdMs));
              if (list.isEmpty) {
                return EmptyState(
                  icon: Icons.quiz_rounded,
                  message: t('noExams'),
                  actionLabel: t('createExam'),
                  onAction: () => _builder(context),
                );
              }
              return ListView.builder(
                padding: const EdgeInsets.fromLTRB(16, 8, 16, 100),
                itemCount: list.length,
                itemBuilder: (_, i) => _examRow(context, list[i]),
              );
            },
          ),
        ),
      ),
      floatingActionButton: FloatingActionButton.extended(
        onPressed: () => _builder(context),
        icon: const Icon(Icons.add_rounded),
        label: Text(t('createExam')),
      ),
    );
  }

  Widget _examRow(BuildContext context, Exam e) {
    List<QuizQ> qs = [];
    try {
      qs = parseQuestions(e.questionsJson);
    } catch (_) {}
    final attempts =
        DB.attempts.values.where((a) => a.examId == e.id).toList();
    final best = attempts.isEmpty
        ? null
        : attempts
            .map((a) => a.maxScore > 0 ? a.score / a.maxScore : 0)
            .reduce((a, b) => a > b ? a : b);
    return Padding(
      padding: const EdgeInsets.only(bottom: 10),
      child: GlassCard(
        onTap: () => Navigator.push(
          context,
          MaterialPageRoute(builder: (_) => ExamDetailScreen(exam: e)),
        ),
        child: Row(
          children: [
            Container(
              width: 46,
              height: 46,
              decoration: BoxDecoration(
                gradient: const LinearGradient(
                    colors: [AppColors.pink, AppColors.violet]),
                borderRadius: BorderRadius.circular(14),
              ),
              child: const Icon(Icons.quiz_rounded, color: Colors.white),
            ),
            const SizedBox(width: 12),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(e.title,
                      style: const TextStyle(
                          fontWeight: FontWeight.w700, fontSize: 15),
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis),
                  Text(
                    '${qs.length} • ${e.durationMin} ${t('min')}${best != null ? ' • ${(best * 100).round()}%' : ''}',
                    style: TextStyle(
                        color: Theme.of(context)
                            .colorScheme
                            .onSurfaceVariant,
                        fontSize: 12),
                  ),
                ],
              ),
            ),
            IconButton(
              icon:
                  const Icon(Icons.delete_rounded, color: AppColors.error),
              onPressed: () async {
                if (await confirmDelete(context)) {
                  for (final a in DB.attempts.values
                      .where((a) => a.examId == e.id)
                      .toList()) {
                    await DB.attempts.delete(a.id);
                  }
                  await DB.exams.delete(e.id);
                }
              },
            ),
          ],
        ),
      ),
    );
  }

  Future<void> _builder(BuildContext context) async {
    // Questions are generated by AI from the PDF library; this entry point
    // guides the user there so the button is never a dead end.
    await showDialog(
      context: context,
      builder: (_) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
        title: Text(t('createExam')),
        content: Text(
          t('genQuestions'),
          style: TextStyle(
              color: Theme.of(context).colorScheme.onSurfaceVariant),
        ),
        actions: [
          TextButton(
              onPressed: () => Navigator.pop(context),
              child: Text(t('cancel'))),
          FilledButton(
            onPressed: () {
              Navigator.pop(context);
              TabNav.go(3, study: 'library');
            },
            child: Text(t('library')),
          ),
        ],
      ),
    );
  }
}

class ExamDetailScreen extends StatelessWidget {
  final Exam exam;
  const ExamDetailScreen({super.key, required this.exam});

  @override
  Widget build(BuildContext context) {
    List<QuizQ> qs = [];
    try {
      qs = parseQuestions(exam.questionsJson);
    } catch (_) {}
    final attempts = DB.attempts.values
        .where((a) => a.examId == exam.id)
        .toList()
      ..sort((a, b) => b.finishedMs.compareTo(a.finishedMs));
    return Scaffold(
      appBar: AppBar(title: Text(exam.title, maxLines: 1)),
      body: AuroraBackground(
        child: ListView(
          padding: const EdgeInsets.fromLTRB(16, 12, 16, 100),
          children: [
            GlassCard(
              child: Column(
                children: [
                  Text('${qs.length} • ${exam.durationMin} ${t('min')}',
                      style: const TextStyle(
                          fontWeight: FontWeight.w700, fontSize: 16)),
                  const SizedBox(height: 12),
                  SizedBox(
                    width: double.infinity,
                    child: GlassButton(
                      label: t('startExam'),
                      icon: Icons.play_arrow_rounded,
                      onPressed: qs.isEmpty
                          ? null
                          : () => Navigator.push(
                                context,
                                MaterialPageRoute(
                                    builder: (_) =>
                                        ExamRunnerScreen(exam: exam, qs: qs)),
                              ),
                    ),
                  ),
                ],
              ),
            ),
            SectionHeader(title: t('attempts')),
            if (attempts.isEmpty)
              GlassCard(child: Text(t('empty')))
            else
              ...attempts.map((a) {
                final pct = a.maxScore > 0
                    ? (a.score / a.maxScore * 100).round()
                    : 0;
                return Padding(
                  padding: const EdgeInsets.only(bottom: 8),
                  child: GlassCard(
                    onTap: () => Navigator.push(
                      context,
                      MaterialPageRoute(
                          builder: (_) =>
                              AttemptReviewScreen(attempt: a, qs: qs)),
                    ),
                    child: Row(
                      children: [
                        _scoreRing(pct),
                        const SizedBox(width: 12),
                        Expanded(
                          child: Text(
                            '${DateTime.fromMillisecondsSinceEpoch(a.finishedMs).day}/${DateTime.fromMillisecondsSinceEpoch(a.finishedMs).month} • ${a.score.toStringAsFixed(0)}/${a.maxScore.toStringAsFixed(0)}',
                            style:
                                const TextStyle(fontWeight: FontWeight.w700),
                          ),
                        ),
                        const Icon(Icons.chevron_right_rounded),
                      ],
                    ),
                  ),
                );
              }),
          ],
        ),
      ),
    );
  }

  Widget _scoreRing(int pct) {
    final c = pct >= 85
        ? AppColors.success
        : pct >= 60
            ? AppColors.warning
            : AppColors.error;
    return SizedBox(
      width: 52,
      height: 52,
      child: Stack(
        alignment: Alignment.center,
        children: [
          CircularProgressIndicator(
              value: pct / 100,
              color: c,
              backgroundColor: c.withValues(alpha: 0.15),
              strokeWidth: 6),
          Text('$pct%',
              style:
                  const TextStyle(fontWeight: FontWeight.w800, fontSize: 13)),
        ],
      ),
    );
  }
}

class ExamRunnerScreen extends StatefulWidget {
  final Exam exam;
  final List<QuizQ> qs;
  const ExamRunnerScreen({super.key, required this.exam, required this.qs});
  @override
  State<ExamRunnerScreen> createState() => _ExamRunnerScreenState();
}

class _ExamRunnerScreenState extends State<ExamRunnerScreen> {
  int _i = 0;
  final Map<int, String> _answers = {};
  late int _remaining;
  Timer? _timer;
  final _shortC = TextEditingController();
  late int _startedMs;

  @override
  void initState() {
    super.initState();
    _remaining = widget.exam.durationMin * 60;
    _startedMs = DateTime.now().millisecondsSinceEpoch;
    _timer = Timer.periodic(const Duration(seconds: 1), (_) {
      if (_remaining <= 1) {
        _submit(auto: true);
      } else {
        setState(() => _remaining--);
      }
    });
  }

  @override
  void dispose() {
    _timer?.cancel();
    _shortC.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final q = widget.qs[_i];
    final mm = (_remaining ~/ 60).toString().padLeft(2, '0');
    final ss = (_remaining % 60).toString().padLeft(2, '0');
    return Scaffold(
      appBar: AppBar(
        title: Text('${_i + 1} / ${widget.qs.length}'),
        actions: [
          Container(
            margin: const EdgeInsets.symmetric(vertical: 10, horizontal: 8),
            padding: const EdgeInsets.symmetric(horizontal: 14),
            decoration: BoxDecoration(
              color: _remaining < 300
                  ? AppColors.error.withValues(alpha: 0.15)
                  : AppColors.primary.withValues(alpha: 0.12),
              borderRadius: BorderRadius.circular(20),
            ),
            child: Center(
              child: Text('$mm:$ss',
                  style: TextStyle(
                      fontWeight: FontWeight.w800,
                      color: _remaining < 300
                          ? AppColors.error
                          : AppColors.primary)),
            ),
          ),
        ],
      ),
      body: AuroraBackground(
        child: Column(
          children: [
            LinearProgressIndicator(
              value: (_i + 1) / widget.qs.length,
              backgroundColor:
                  AppColors.primary.withValues(alpha: 0.15),
              color: AppColors.primary,
              minHeight: 6,
            ),
            Expanded(
              child: ListView(
                padding: const EdgeInsets.all(16),
                children: [
                  GlassCard(
                    child: Text(q.q,
                        style: const TextStyle(
                            fontSize: 17,
                            fontWeight: FontWeight.w700,
                            height: 1.7)),
                  ),
                  const SizedBox(height: 12),
                  if (q.type == 'short')
                    TextField(
                      controller: _shortC,
                      maxLines: 4,
                      decoration: InputDecoration(
                          labelText: t('shortAnswer'),
                          hintText: '...'),
                      onChanged: (v) => _answers[_i] = v,
                    )
                  else
                    ..._options(q),
                ],
              ),
            ),
            SafeArea(
              child: Padding(
                padding: const EdgeInsets.fromLTRB(16, 4, 16, 12),
                child: Row(
                  children: [
                    Expanded(
                      child: OutlinedButton(
                        onPressed:
                            _i > 0 ? () => _go(_i - 1) : null,
                        child: Text(t('prev')),
                      ),
                    ),
                    const SizedBox(width: 10),
                    Expanded(
                      child: _i < widget.qs.length - 1
                          ? GlassButton(
                              label: t('next'),
                              onPressed: () => _go(_i + 1))
                          : GlassButton(
                              label: t('submitExam'),
                              secondary: true,
                              onPressed: () => _submit()),
                    ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }

  List<Widget> _options(QuizQ q) {
    final opts = q.type == 'tf' ? [t('true_'), t('false_')] : q.options;
    return [
      RadioGroup<String>(
        groupValue: _answers[_i],
        onChanged: (v) => setState(() => _answers[_i] = v ?? ''),
        child: Column(
          children: [
            for (var k = 0; k < opts.length; k++)
              Padding(
                padding: const EdgeInsets.only(bottom: 8),
                child: GlassCard(
                  padding: const EdgeInsets.symmetric(
                      horizontal: 8, vertical: 4),
                  onTap: () => setState(
                      () => _answers[_i] = _storeVal(q, k, opts[k])),
                  child: RadioListTile<String>(
                    value: _storeVal(q, k, opts[k]),
                    title: Text(opts[k]),
                    activeColor: AppColors.primary,
                    contentPadding: EdgeInsets.zero,
                  ),
                ),
              ),
          ],
        ),
      ),
    ];
  }

  /// For tf questions store canonical 'true'/'false'.
  String _storeVal(QuizQ q, int k, String label) {
    if (q.type == 'tf') return k == 0 ? 'true' : 'false';
    return label;
  }

  void _go(int i) {
    if (widget.qs[_i].type == 'short') _answers[_i] = _shortC.text;
    _shortC.text = _answers[i] ?? '';
    setState(() => _i = i);
  }

  Future<void> _submit({bool auto = false}) async {
    _timer?.cancel();
    if (widget.qs[_i].type == 'short') _answers[_i] = _shortC.text;
    final g = gradeExam(widget.qs, _answers);
    final id = newId();
    final attempt = ExamAttempt(
      id: id,
      examId: widget.exam.id,
      answersJson: jsonEncode(
          {for (final e in _answers.entries) '${e.key}': e.value}),
      score: g.score,
      maxScore: g.maxScore,
      startedMs: _startedMs,
      finishedMs: DateTime.now().millisecondsSinceEpoch,
    );
    await DB.attempts.put(id, attempt);
    if (!mounted) return;
    if (auto) showSnack(context, t('timeUp'));
    Navigator.pushReplacement(
      context,
      MaterialPageRoute(
          builder: (_) => AttemptReviewScreen(
              attempt: attempt, qs: widget.qs, fresh: true)),
    );
  }
}

class AttemptReviewScreen extends StatelessWidget {
  final ExamAttempt attempt;
  final List<QuizQ> qs;
  final bool fresh;
  const AttemptReviewScreen(
      {super.key, required this.attempt, required this.qs, this.fresh = false});

  @override
  Widget build(BuildContext context) {
    final pct =
        attempt.maxScore > 0 ? (attempt.score / attempt.maxScore * 100).round() : 0;
    final verdict =
        pct >= 85 ? t('excellent') : pct >= 60 ? t('good') : t('needsWork');
    Map<String, dynamic> answers = {};
    try {
      answers = jsonDecode(attempt.answersJson) as Map<String, dynamic>;
    } catch (_) {}
    return Scaffold(
      appBar: AppBar(title: Text(t('reviewAnswers'))),
      body: AuroraBackground(
        child: ListView(
          padding: const EdgeInsets.fromLTRB(16, 12, 16, 40),
          children: [
            GlassCard(
              gradient: const [AppColors.primary, AppColors.violet],
              child: Column(
                children: [
                  Text(t('yourScore'),
                      style: const TextStyle(color: Colors.white70)),
                  Text('$pct%',
                      style: const TextStyle(
                          color: Colors.white,
                          fontWeight: FontWeight.w800,
                          fontSize: 44)),
                  Text(
                      '${attempt.score.toStringAsFixed(0)} / ${attempt.maxScore.toStringAsFixed(0)} • $verdict',
                      style: const TextStyle(color: Colors.white)),
                ],
              ),
            ),
            const SizedBox(height: 12),
            for (var i = 0; i < qs.length; i++)
              _qReview(context, qs[i], '${answers['$i'] ?? ''}', i),
            if (fresh)
              GlassButton(
                  label: t('finish'),
                  onPressed: () => Navigator.pop(context)),
          ],
        ),
      ),
    );
  }

  Widget _qReview(BuildContext context, QuizQ q, String given, int i) {
    final isShort = q.type == 'short';
    final ok = !isShort &&
        given.trim().isNotEmpty &&
        given.trim().toLowerCase() == q.answer.trim().toLowerCase();
    return Padding(
      padding: const EdgeInsets.only(bottom: 10),
      child: GlassCard(
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Icon(
                    isShort
                        ? Icons.edit_note_rounded
                        : ok
                            ? Icons.check_circle_rounded
                            : Icons.cancel_rounded,
                    color: isShort
                        ? AppColors.warning
                        : ok
                            ? AppColors.success
                            : AppColors.error),
                const SizedBox(width: 8),
                Expanded(
                    child: Text('${i + 1}. ${q.q}',
                        style: const TextStyle(
                            fontWeight: FontWeight.w700, fontSize: 15))),
              ],
            ),
            const SizedBox(height: 8),
            if (isShort)
              Text(t('notGradedAuto'),
                  style: const TextStyle(
                      color: AppColors.warning, fontSize: 13))
            else ...[
              Text('${t('yourAnswer')}: ${given.isEmpty ? '—' : given}',
                  style: TextStyle(
                      color: ok ? AppColors.success : AppColors.error,
                      fontWeight: FontWeight.w600)),
              Text('${t('correctAnswer')}: ${q.answer}',
                  style: const TextStyle(
                      color: AppColors.success,
                      fontWeight: FontWeight.w600)),
            ],
            if (q.explanation.isNotEmpty)
              Padding(
                padding: const EdgeInsets.only(top: 6),
                child: Text(q.explanation,
                    style: TextStyle(
                        color: Theme.of(context)
                            .colorScheme
                            .onSurfaceVariant,
                        fontSize: 13)),
              ),
          ],
        ),
      ),
    );
  }
}
