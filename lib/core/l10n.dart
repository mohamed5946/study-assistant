String t(String key) => L.t(key);

class LangScope extends StatelessWidget {
  final Widget child;
  const LangScope({super.key, required this.child});

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder<String>(
      valueListenable: L.lang,
      builder: (_, code, __) => Directionality(
        textDirection: code == 'ar' ? TextDirection.rtl : TextDirection.ltr,
        child: Localizations.override(
          context: context,
          locale: Locale(code),
          child: child,
        ),
      ),
    );
  }
}
